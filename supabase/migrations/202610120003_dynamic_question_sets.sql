create table if not exists public.exam_question_sets (
  set_number integer generated by default as identity primary key,
  name text not null check (nullif(trim(name), '') is not null and length(trim(name)) <= 80)
);

insert into public.exam_question_sets (set_number, name)
select set_number, 'Set ' || set_number
from generate_series(1, 4) as generated(set_number)
on conflict (set_number) do nothing;

select setval(
  pg_get_serial_sequence('public.exam_question_sets', 'set_number'),
  (select max(set_number) from public.exam_question_sets),
  true
);

create unique index if not exists exam_question_sets_name_unique
  on public.exam_question_sets (lower(trim(name)));

create or replace function public.prevent_question_set_number_change()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.set_number is distinct from old.set_number then
    raise exception 'Question set numbers are permanent and cannot be changed.';
  end if;
  return new;
end;
$$;

drop trigger if exists prevent_question_set_number_change on public.exam_question_sets;
create trigger prevent_question_set_number_change
  before update of set_number on public.exam_question_sets
  for each row
  execute function public.prevent_question_set_number_change();

