create or replace function public.prevent_submitted_batch_question_set_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    if exists (select 1 from public.submissions where batch = new.batch) then
      raise exception 'Question set assignment cannot be added after submissions exist for batch %.', new.batch;
    end if;
    return new;
  end if;

  if tg_op = 'DELETE' then
    if exists (select 1 from public.submissions where batch = old.batch) then
      raise exception 'Question set assignment cannot be deleted after submissions exist for batch %.', old.batch;
    end if;
    return old;
  end if;

  if new.question_set is distinct from old.question_set
    and exists (select 1 from public.submissions where batch = old.batch) then
    raise exception 'Question set assignment cannot be changed after submissions exist for batch %.', old.batch;
  end if;

  return new;
end;
$$;

drop trigger if exists prevent_submitted_batch_question_set_change on public.exam_batch_question_sets;
create trigger prevent_submitted_batch_question_set_change
  before insert or update or delete on public.exam_batch_question_sets
  for each row
  execute function public.prevent_submitted_batch_question_set_change();

create or replace function public.ensure_submission_batch_question_set()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  requested_set integer;
  assigned_set integer;
begin
  if new.batch is null or nullif(trim(new.batch), '') is null then
    return new;
  end if;

  requested_set := coalesce(nullif(new.answers ->> 'question_set', '')::integer, 1);

  select question_set into assigned_set
  from public.exam_batch_question_sets
  where batch = new.batch
  for update;

  if not found then
    insert into public.exam_batch_question_sets (batch, question_set)
    values (new.batch, requested_set)
    on conflict (batch) do nothing;

    select question_set into assigned_set
    from public.exam_batch_question_sets
    where batch = new.batch
    for update;
  end if;

  if assigned_set is distinct from requested_set then
    raise exception 'Submitted question set % does not match batch % assignment %.',
      requested_set, new.batch, assigned_set;
  end if;

  return new;
end;
$$;

drop trigger if exists ensure_submission_batch_question_set on public.submissions;
create trigger ensure_submission_batch_question_set
  before insert on public.submissions
  for each row
  execute function public.ensure_submission_batch_question_set();

alter table public.exam_question_sets enable row level security;

drop policy if exists "Approved users can read exam question sets" on public.exam_question_sets;
create policy "Approved users can read exam question sets"
  on public.exam_question_sets for select
  to authenticated
  using (exists (
    select 1 from public.profiles
    where profiles.id = auth.uid() and profiles.approved = true
  ));

drop policy if exists "Exam editors can add question sets" on public.exam_question_sets;
create policy "Exam editors can add question sets"
  on public.exam_question_sets for insert
  to authenticated
  with check (public.has_teacher_permission('exam', 'edit'));

drop policy if exists "Exam editors can rename question sets" on public.exam_question_sets;
create policy "Exam editors can rename question sets"
  on public.exam_question_sets for update
  to authenticated
  using (public.has_teacher_permission('exam', 'edit'))
  with check (public.has_teacher_permission('exam', 'edit'));

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'exam_question_sets'
  ) then
    alter publication supabase_realtime add table public.exam_question_sets;
  end if;
end
$$;

revoke all on function public.prevent_submitted_batch_question_set_change() from public, anon, authenticated;
